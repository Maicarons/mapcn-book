    for fn, repls in REPL.items():
        path = os.path.join(CHAPTERS_DIR, fn)
        with open(path, encoding="utf-8") as f:
            text = f.read()
        applied = 0
        for old, new in repls:
            if old in text:
                text = text.replace(old, new, 1)
                applied += 1
            else:
                print("  [UNMATCHED in %s] %r" % (fn, old[:60]))
        with open(path, "w", encoding="utf-8") as f:
            f.write(text)
        total_applied += applied
        print("%s: applied %d/%d" % (fn, applied, len(repls)))
    print("TOTAL applied:", total_applied)

    # post-check: any double-space left in prose (outside fences)?
    print("\n=== remaining double-space in prose ===")
    left = 0
    for fn in REPL:
        path = os.path.join(CHAPTERS_DIR, fn)
        in_fence = False
        for ln in open(path, encoding="utf-8"):
            if ln.strip().startswith("```"):
                in_fence = not in_fence
                continue
            if in_fence:
                continue
            if "  " in ln:
                left += 1
                print("  %s: %s" % (fn, ln.rstrip("\n")[:100]))
    print("remaining prose double-space lines:", left)

